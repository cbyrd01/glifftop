#!/usr/bin/env bash
# The full gate: run before every commit. One summary line per step; on failure, only the
# failing step's output is shown.
set -euo pipefail
cd "$(dirname "$0")/.."

log=$(mktemp)
trap 'rm -f "$log" "$log.tests"' EXIT

source scripts/gate-step.sh

# fixture_drift — regenerate the golden fixtures and the synthetic video planes from the pinned
# upstream Rust into a temp dir and fail if they differ from the ones the Swift tests read
# (changed, added or gone).
# Cargo is offline here: a fresh clone first runs scripts/cargo-net.sh fetch --locked.
fixture_drift() {
    local out rc=0 kind committed
    out=$(mktemp -d)
    for kind in fixtures:GliffProtocolTests/Fixtures planes:GliffVideoTests/Fixtures/synthetic/planes; do
        committed="Packages/GliffKit/Tests/${kind#*:}"
        kind=${kind%%:*}
        if ! cargo run --quiet --locked --manifest-path tools/fake-server/Cargo.toml -- "$kind" "$out/$kind"; then
            echo "$kind generator failed (fresh clone? scripts/cargo-net.sh fetch --locked)"
            rc=1
        elif ! diff -r -x '.*' "$out/$kind" "$committed"; then
            echo "$kind changed: the pinned upstream Rust no longer makes the committed bytes"
            rc=1
        fi
    done
    rm -rf "$out"
    return "$rc"
}

# script_tests — the shell scripts' own tests (stub tools on PATH, no network).
script_tests() {
    for test in scripts/tests/*-test.sh; do "$test" || return 1; done
}

# fake_server — build the fake server the session tests run, and run its own tests. The
# target dir is explicit so a CARGO_TARGET_DIR in the environment can't move the binary.
fake_server() {
    set -- --quiet --locked --manifest-path tools/fake-server/Cargo.toml --target-dir tools/fake-server/target
    cargo build "$@" && cargo test "$@"
}

# encode_fixtures — build (swift test builds every target) and test tools/encode-fixtures. The
# gate never runs the tool: its VideoToolbox output isn't byte-stable across OS releases, so
# the committed streams are regenerated by hand (tools/encode-fixtures/README.md).
encode_fixtures() {
    swift test --package-path tools/encode-fixtures
}

# gliffkit_tests — build GliffKit and its tests, then run them against the built fake server.
# A run still going after 10 minutes, about four times its usual length, is ended, and the
# tests still running are named from --verbose's start lines. `script` gives the tests a
# terminal, so their output is line-buffered and an ended run loses none of it; Swift
# Testing's SF Symbols markers stay off, as the names are read from its plain ones.
# No -q: in SwiftPM 6.4 it hides the compiler's diagnostics.
gliffkit_tests() {
    local out rc=0
    swift build --build-tests --package-path Packages/GliffKit || return 1
    out="$log.tests"
    GLIFFTOP_FAKE_SERVER="$PWD/tools/fake-server/target/debug/glifftop-fake-server" \
        SWT_SF_SYMBOLS_ENABLED=0 scripts/time-limit.sh 600 script -q /dev/null \
        swift test --skip-build --verbose --package-path Packages/GliffKit </dev/null >"$out" 2>&1 || rc=$?
    sed '1s/^\^D\x08\x08//; s/\r$//' "$out"
    [ "$rc" -ne 124 ] || scripts/unfinished-tests.sh <"$out"
    return "$rc"
}

step secrets gitleaks git --redact --no-banner
step format swift format lint --strict --parallel --recursive Glifftop \
    Packages/GliffKit/Package.swift Packages/GliffKit/Sources Packages/GliffKit/Tests \
    tools/encode-fixtures/Package.swift tools/encode-fixtures/Sources tools/encode-fixtures/Tests
step sources scripts/check-sources.sh
step xcodeproj scripts/check-xcodeproj.sh
step script-tests script_tests
step fake-server fake_server
step fixture-drift fixture_drift
step encode-fixtures encode_fixtures
step gliffkit-tests gliffkit_tests
step app-build scripts/app-build.sh
step ios-check scripts/ios-check.sh
echo "gate passed"
